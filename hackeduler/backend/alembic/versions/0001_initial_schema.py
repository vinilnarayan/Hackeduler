"""Initial schema for Hackeduler.

Key integrity mechanisms:
  * booking_resource_locks holds ONE ROW PER (resource, eligible working date)
    reserved by a booking. A partial UNIQUE index on (resource_id, work_date)
    over active, non-forced locks guarantees at the database level that two
    normal reservations can never hold the same resource on the same working day,
    regardless of application bugs or concurrent transactions.
  * audit_logs and booking_status_history are append-only: triggers reject
    UPDATE, DELETE and TRUNCATE.

Revision ID: 0001
"""
